"""Validation against a NIST Statistical Reference Dataset (StRD).

Misra1a — nonlinear regression, certified values from
https://www.itl.nist.gov/div898/strd/nls/data/misra1a.shtml
Model: y = b1 * (1 - exp(-b2 * x)), 14 observations, 12 degrees of freedom.
"""

import numpy as np
import pytest

from sciflow.fit import fit
from sciflow.models import expression_model

MISRA1A_Y = np.array([10.07, 14.73, 17.94, 23.93, 29.61, 35.18, 40.02,
                      44.82, 50.76, 55.05, 61.01, 66.40, 75.47, 81.78])
MISRA1A_X = np.array([77.6, 114.9, 141.1, 190.8, 239.9, 289.0, 332.8,
                      378.4, 434.8, 477.3, 536.8, 593.1, 689.1, 760.0])

CERTIFIED = {
    "b1": (2.3894212918e02, 2.7070075241e00),
    "b2": (5.5015643181e-04, 7.2668688436e-06),
    "residual_ss": 1.2455138894e-01,
    "residual_sd": 1.0187876330e-01,
}


@pytest.mark.parametrize("start", [[500.0, 1e-4], [250.0, 5e-4]])  # NIST start 1 and start 2
def test_misra1a_certified_values(start):
    model = expression_model("b1*(1-exp(-b2*x))", ["b1", "b2"], initial_guess=start)
    result = fit(MISRA1A_X, MISRA1A_Y, model)

    for name, (value, sd) in (("b1", CERTIFIED["b1"]), ("b2", CERTIFIED["b2"])):
        assert result.params[name] == pytest.approx(value, rel=1e-7)
        assert result.errors[name] == pytest.approx(sd, rel=1e-5)

    ss = float(np.sum(result.residuals**2))
    assert ss == pytest.approx(CERTIFIED["residual_ss"], rel=1e-8)
    assert result.residual_sd == pytest.approx(CERTIFIED["residual_sd"], rel=1e-8)
    assert result.dof == 12


